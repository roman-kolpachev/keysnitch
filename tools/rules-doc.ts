// Writes docs/rules.md: every built-in rule, grouped by company.
// Usage: node tools/rules-doc.ts. test/docs.test.ts checks that the file is
// up to date.

import { writeFileSync } from "node:fs";
import { rules } from "../src/rules/index.ts";
import { GITLEAKS_VERSION, gitleaksSkipped } from "../src/rules/gitleaks.ts";
import { vendors } from "../src/search.ts";

function cell(text: string): string {
  return text.replaceAll("|", "\\|");
}

export function rulesDoc(): string {
  const lines: string[] = [
    "# Built-in rules",
    "",
    `keysnitch has ${String(rules.length)} built-in rules from ${String(vendors(rules).length)} companies and projects.`,
    `${String(rules.filter((rule) => rule.source?.startsWith("gitleaks") ?? false).length)} come from gitleaks ${GITLEAKS_VERSION} (some with changes, see tools/gitleaks/overrides.ts and tools/gitleaks/also.ts), the rest are keysnitch's own (src/rules/keysnitch.ts).`,
    "",
    "This file is generated by `node tools/rules-doc.ts`. Do not edit it by hand.",
    "",
    "## gitleaks rules that are not built in",
    "",
    "| Rule | Why |",
    "| --- | --- |",
    ...gitleaksSkipped.map((entry) => `| ${entry.id} | ${cell(entry.reason)} |`),
    "",
    "## Rules by company",
    "",
  ];
  for (const { vendor } of vendors(rules)) {
    lines.push(`### ${vendor}`, "", "| Rule | Name | Severity | From |", "| --- | --- | --- | --- |");
    const own = rules.filter((rule) => rule.vendor === vendor).sort((a, b) => a.id.localeCompare(b.id, "en"));
    for (const rule of own) {
      const from = rule.source?.startsWith("gitleaks") === true ? "gitleaks" : "keysnitch";
      lines.push(`| ${rule.id} | ${cell(rule.label)} | ${rule.severity} | ${from} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (process.argv[1]?.endsWith("rules-doc.ts") === true) {
  writeFileSync(new URL("../docs/rules.md", import.meta.url), rulesDoc());
  process.stdout.write(`wrote docs/rules.md with ${String(rules.length)} rules\n`);
}
