// Writes src/rules/gitleaks.ts from third_party/gitleaks/gitleaks.toml.
// Usage: node tools/gitleaks/import.ts          (write the file)
//        node tools/gitleaks/import.ts --report (print what fails, write nothing)

import { writeFileSync } from "node:fs";
import { buildGitleaksRules } from "./build.ts";

const root = new URL("../../", import.meta.url);
const { version, specs, skipped, failures } = buildGitleaksRules();

if (process.argv.includes("--report")) {
  process.stdout.write(
    `${String(specs.length)} converted, ${String(skipped.length)} skipped, ${String(failures.length)} failing\n`,
  );
  for (const failure of failures) process.stdout.write(`${failure}\n`);
  for (const skip of skipped) process.stdout.write(`skipped ${skip.id}: ${skip.reason}\n`);
} else {
  if (failures.length > 0) {
    process.stderr.write(`${failures.join("\n")}\n`);
    process.exit(1);
  }
  const body = [
    "// Generated by tools/gitleaks/import.ts from third_party/gitleaks/gitleaks.toml. Do not edit.",
    "// The patterns are adapted from gitleaks (MIT license, see NOTICE.md).",
    "",
    'import type { RuleSpec } from "../types.ts";',
    "",
    `export const GITLEAKS_VERSION = ${JSON.stringify(version)};`,
    "",
    `export const gitleaksRules: readonly RuleSpec[] = ${JSON.stringify(specs, null, 2)};`,
    "",
    "/** gitleaks rules keysnitch does not take as they are, and why. */",
    `export const gitleaksSkipped: readonly { readonly id: string; readonly reason: string }[] = ${JSON.stringify(skipped, null, 2)};`,
    "",
  ].join("\n");
  writeFileSync(new URL("src/rules/gitleaks.ts", root), body);
  process.stdout.write(`wrote ${String(specs.length)} rules, skipped ${String(skipped.length)}\n`);
}
